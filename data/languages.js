export const isSupportedLanguage = (language) =>
  LANGUAGES.some((item) => item.id === language);

export const getLanguageDefinition = (language) =>
  LANGUAGES.find((item) => item.id === language) ||
  LANGUAGES.find((item) => item.id === DEFAULT_LANGUAGE);

export const getUiCopy = (language) =>
  UI_COPY[isSupportedLanguage(language) ? language : DEFAULT_LANGUAGE] ||
  UI_COPY[DEFAULT_LANGUAGE];

const collectStringPaths = (value, path = [], output = []) => {
  if (typeof value === "string") {
    output.push([path, value]);
    return output;
  }

  Object.entries(value || {}).forEach(([key, child]) => {
    collectStringPaths(child, [...path, key], output);
  });

  return output;
};

const readPath = (value, path) =>
  path.reduce(
    (current, key) =>
      current && Object.prototype.hasOwnProperty.call(current, key)
        ? current[key]
        : undefined,
    value
  );

const englishSourcePaths = new Map();

collectStringPaths(UI_COPY[DEFAULT_LANGUAGE]).forEach(([path, value]) => {
  if (!englishSourcePaths.has(value)) {
    englishSourcePaths.set(value, path);
  }
});

export const getUiText = (language, sourceText) => {
  const path = englishSourcePaths.get(sourceText);

  if (!path) {
    return sourceText;
  }

  const localized = readPath(getUiCopy(language), path);

  return typeof localized === "string" ? localized : sourceText;
};
