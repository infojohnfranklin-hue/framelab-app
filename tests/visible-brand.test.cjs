const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const {parse} = require('@babel/parser');
const path = require('node:path');
const root=path.join(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
test('all seven UI translations use Premivate and retain language storage key',()=>{
 const s=read('data/languages.js');
 const copy=vm.runInNewContext(s.replace(/export /g,'')+';({LANGUAGES,getUiCopy,getUiText,LANGUAGE_STORAGE_KEY})');
 assert.equal(copy.LANGUAGE_STORAGE_KEY,'framelab_language');
 assert.equal(copy.LANGUAGES.length,7);
 for(const lang of copy.LANGUAGES){const text=JSON.stringify(copy.getUiCopy(lang.id));assert.doesNotMatch(text,/framelab/i);assert.match(text,/Premivate/);}
});
test('sidebar subscription copy follows the selected language and preserves Pro gates',()=>{
 const s=read('data/languages.js');
 const copy=vm.runInNewContext(s.replace(/export /g,'')+';({LANGUAGES,getUiCopy,getUiText,LANGUAGE_STORAGE_KEY})');
 const sidebar=read('components/Sidebar.js');
 assert.equal(copy.getUiText('English','Unlimited cinematic AI reel generations.'),'Unlimited cinematic AI reel generations.');
 assert.equal(copy.getUiText('Deutsch','Unlimited cinematic AI reel generations.'),'Unbegrenzte filmische KI-Reel-Generierungen.');
 assert.equal(copy.getUiText('English','Pro Unlimited Active'),'Pro Unlimited Active');
 assert.equal(copy.getUiText('Deutsch','Pro Unlimited Active'),'Pro Unlimited aktiv');
 assert.match(sidebar, /\{t\("Unlimited cinematic AI reel generations\."\)\}/);
 assert.match(sidebar, /\{userPlan === "pro" \? t\("Pro Unlimited Active"\) : "Go Pro"\}/);
 assert.match(sidebar, /\{userPlan !== "pro" && \([\s\S]*?\{t\("Upgrade to Pro"\)\}/);
 assert.match(sidebar, /if \(userPlan === "pro"\) \{\s*setShowAlreadyProDialog\(true\)/);
});
test('visible logo, package headings and generated-by branding use PREMIVATE',()=>{
 const sidebar=read('components/Sidebar.js');
 assert.ok(sidebar.includes('/videos/logo/premivate-logo.png'));
 assert.ok(sidebar.includes('alt="PREMIVATE"'));
 assert.ok(fs.existsSync(path.join(root,'public/videos/logo/premivate-logo.png')));
 const index=read('pages/index.js');
 assert.ok(index.includes('PREMIVATE CREATIVE PACKAGE'));
 assert.ok(index.includes('GENERATED BY PREMIVATE'));
 assert.ok(index.includes('"framelab_history"'));
 assert.doesNotMatch(read('pages/api/generate.js'),/#FrameLab\b/);
});
test('affected UI modules parse as JS/JSX',()=>{
 for(const f of ['components/Sidebar.js','data/languages.js','data/directorModes.js','pages/index.js','pages/settings.js','pages/dashboard.js','pages/pricing.js'])parse(read(f),{sourceType:'module',plugins:['jsx']});
});
test('Generate demo and matrix seed use John Franklin / Noir Current',()=>{
 const index=read('pages/index.js');
 assert.equal((index.match(/useState\("John Franklin"\)/g)||[]).length,1);
 assert.equal((index.match(/useState\("Noir Current"\)/g)||[]).length,1);
 assert.equal((index.match(/setArtist\("John Franklin"\)/g)||[]).length,1);
 assert.equal((index.match(/setTrack\("Noir Current"\)/g)||[]).length,1);
 assert.doesNotMatch(index,/Aurora Wolves|Northern Migration/);
});
